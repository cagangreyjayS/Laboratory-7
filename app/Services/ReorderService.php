<?php

namespace App\Services;

use App\Models\InventoryProduct;
use App\Models\PurchaseOrder;
use App\Models\PurchaseOrderItem;
use Illuminate\Support\Facades\DB;

class ReorderService
{
    /**
     * Calculate Reorder Point: (Average Daily Usage * Lead Time) + Safety Stock
     */
    public function calculateReorderPoint(InventoryProduct $product, int $leadTimeDays): int
    {
        // Estimate average daily usage (fallback to 1 if no transactions exist)
        $averageDailyUsage = $product->transactions()
            ->where('type', 'out')
            ->where('created_at', '>=', now()->subDays(30))
            ->sum('quantity') / 30;
            
        $averageDailyUsage = max(ceil($averageDailyUsage), 1);
        $safetyStock = $product->safety_stock ?? 10;

        return (int) (($averageDailyUsage * $leadTimeDays) + $safetyStock);
    }

    /**
     * Get products whose current stock is at or below their calculated reorder point.
     */
    public function getProductsNeedingReorder()
    {
        $products = InventoryProduct::with('supplier')->get();
        $reorderList = collect();

        foreach ($products as $product) {
            $leadTime = $product->supplier->lead_time_days ?? 7;
            $reorderPoint = $this->calculateReorderPoint($product, $leadTime);

            if ($product->quantity <= $reorderPoint) {
                $product->calculated_reorder_point = $reorderPoint;
                $product->suggested_order_qty = max(($reorderPoint * 2) - $product->quantity, 10);
                $reorderList->push($product);
            }
        }

        return $reorderList;
    }

    /**
     * Group products needing reorder by supplier and generate draft purchase orders.
     */
    public function generatePurchaseOrders($userId = 1)
    {
        $productsNeedingReorder = $this->getProductsNeedingReorder();
        $groupedBySupplier = $productsNeedingReorder->groupBy('supplier_id');
        $generatedOrders = [];

        foreach ($groupedBySupplier as $supplierId => $products) {
            if (!$supplierId) continue;

            // Prevent duplicate active purchase orders for the same supplier
            $existingActiveOrder = PurchaseOrder::where('supplier_id', $supplierId)
                ->whereIn('status', ['draft', 'pending', 'approved', 'sent'])
                ->exists();

            if ($existingActiveOrder) {
                continue; // Skip to avoid duplicate orders
            }

            DB::transaction(function () use ($supplierId, $products, $userId, &$generatedOrders) {
                $subtotal = 0;
                $itemsData = [];

                foreach ($products as $product) {
                    $qty = $product->suggested_order_qty;
                    $price = $product->unit_price ?? 10.00;
                    $subtotal += $qty * $price;

                    $itemsData[] = [
                        'inventory_product_id' => $product->id,
                        'quantity_ordered' => $qty,
                        'unit_price' => $price,
                        'quantity_received' => 0,
                    ];
                }

                $tax = $subtotal * 0.12;
                $total = $subtotal + $tax;

                $po = PurchaseOrder::create([
                    'reference_number' => 'AUTO-PO-' . date('Ymd') . '-' . rand(100, 999),
                    'supplier_id' => $supplierId,
                    'status' => 'draft',
                    'order_date' => now(),
                    'expected_delivery_date' => now()->addDays(7),
                    'subtotal' => $subtotal,
                    'tax' => $tax,
                    'total_amount' => $total,
                    'notes' => 'Automatically generated by system reorder detection.',
                    'created_by' => $userId,
                ]);

                foreach ($itemsData as $item) {
                    $po->items()->create($item);
                }

                $generatedOrders[] = $po;
            });
        }

        return $generatedOrders;
    }
}